# exports.R
# Writes the palette to non-R formats in inst/exports/, from the package itself,
# so all formats stay in sync. Run from the package root after changing colours:
#   Rscript data-raw/exports.R

devtools::load_all(quiet = TRUE)
out <- "inst/exports"

# ---- CSV: everything in one table -----------------------------------------------
ramps <- names(seidl_colours)   # one sequential ramp per categorical colour
seq_rows <- do.call(rbind, lapply(ramps, \(p)
  data.frame(set = paste0("seq-", p), name = paste0(p, "-", 1:9), hex = seidl_seq(9, p))))
all <- rbind(
  data.frame(set = "categorical", name = names(seidl_colours), hex = unname(seidl_colours)),
  data.frame(set = "categorical", name = "other", hex = seidl_grey),
  data.frame(set = "tint", name = names(seidl_tints), hex = unname(seidl_tints)),
  seq_rows,
  data.frame(set = "diverging", name = paste0("div-", 1:9), hex = seidl_div(9))
)
write.csv(all, file.path(out, "seidlpal-colours.csv"), row.names = FALSE)

# ---- SCSS variables -----------------------------------------------------------------
scss <- c("// seidlpal colours, generated by data-raw/exports.R; do not edit by hand",
          "", "// Categorical, in usage order",
          sprintf("$seidl-%s: %s;", names(seidl_colours), seidl_colours),
          sprintf("$seidl-other: %s;", seidl_grey),
          "", "// Light tints (box fills, highlights; dark text on top)",
          sprintf("$seidl-%s-tint: %s;", names(seidl_tints), seidl_tints),
          unlist(lapply(ramps, \(p) c("", sprintf("// Sequential %s, light (1) to dark (9)", p),
                                      sprintf("$seidl-seq-%s-%d: %s;", p, 1:9, seidl_seq(9, p))))))
writeLines(scss, file.path(out, "seidlpal.scss"))

# ---- draw.io configuration ---------------------------------------------------------
# Paste into draw.io: Extras > Configuration (web/desktop), then Apply and reload.
# customPresetColors: the colour picker's preset row (hex without #).
# customColorSchemes: style presets in the Format panel (tint fill + full-colour border).
presets <- sub("#", "", c(seidl_colours, seidl_grey))
schemes <- lapply(names(seidl_colours), \(n)
  sprintf('{"fill": "%s", "stroke": "%s", "font": "#2A2A26"}', seidl_tints[[n]], seidl_colours[[n]]))
json <- c("{",
          sprintf('  "customPresetColors": [%s],', paste0('"', presets, '"', collapse = ", ")),
          '  "customColorSchemes": [[',
          paste0("    ", unlist(schemes), collapse = ",\n"),
          "  ]]",
          "}")
writeLines(json, file.path(out, "drawio-config.json"))

message("Wrote ", paste(list.files(out), collapse = ", "))
